UPDATE public.reservations
SET
  guest_name = COALESCE(guest_name, name),
  name = COALESCE(name, guest_name),
  phone_number = COALESCE(phone_number, phone),
  phone = COALESCE(phone, phone_number),
  email = COALESCE(email, 'unknown@example.invalid'),
  no_of_guests = COALESCE(no_of_guests, guests),
  guests = COALESCE(guests, no_of_guests),
  slot = COALESCE(slot, time),
  time = COALESCE(time, slot),
  reservation_start = COALESCE(
    reservation_start,
    CASE
      WHEN date IS NOT NULL AND COALESCE(slot, time) IS NOT NULL
      THEN (date::timestamp + COALESCE(slot, time)) AT TIME ZONE current_setting('TIMEZONE')
    END
  ),
  reservation_end = COALESCE(
    reservation_end,
    CASE
      WHEN date IS NOT NULL AND COALESCE(slot, time) IS NOT NULL
      THEN ((date::timestamp + COALESCE(slot, time)) AT TIME ZONE current_setting('TIMEZONE')) + interval '90 minutes'
    END
  ),
  status = upper(status),
  source = COALESCE(source, 'Walk In'),
  created_at = COALESCE(created_at, now()),
  updated_at = COALESCE(updated_at, now());

