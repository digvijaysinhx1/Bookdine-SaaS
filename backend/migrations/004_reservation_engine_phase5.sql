ALTER TABLE public.reservations
ADD CONSTRAINT reservations_guest_name_not_empty
  CHECK (length(btrim(guest_name)) > 0),
ADD CONSTRAINT reservations_phone_number_not_empty
  CHECK (length(btrim(phone_number)) > 0),
ADD CONSTRAINT reservations_email_not_empty
  CHECK (length(btrim(email)) > 0),
ADD CONSTRAINT reservations_source_not_empty
  CHECK (length(btrim(source)) > 0),
ADD CONSTRAINT reservations_guests_positive
  CHECK (no_of_guests > 0 AND guests > 0),
ADD CONSTRAINT reservations_status_check
  CHECK (status IN ('CONFIRMED', 'SEATED', 'COMPLETED', 'NO_SHOW', 'CANCELLED')),
ADD CONSTRAINT reservations_time_range_check
  CHECK (reservation_end = reservation_start + interval '90 minutes');

DROP INDEX IF EXISTS reservations_unique_active_slot;

CREATE INDEX IF NOT EXISTS reservations_tenant_start_idx
ON public.reservations (tenant_id, reservation_start);

CREATE INDEX IF NOT EXISTS reservations_tenant_phone_active_idx
ON public.reservations (tenant_id, phone_number)
WHERE status IN ('CONFIRMED', 'SEATED');

CREATE UNIQUE INDEX IF NOT EXISTS reservations_unique_active_table_slot
ON public.reservations (tenant_id, table_id, reservation_start)
WHERE status IN ('CONFIRMED', 'SEATED') AND table_id IS NOT NULL;

ALTER TABLE public.reservations
