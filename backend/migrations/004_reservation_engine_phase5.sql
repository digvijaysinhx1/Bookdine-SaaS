ALTER TABLE public.reservations
ADD CONSTRAINT reservations_no_active_table_overlap
EXCLUDE USING gist (
  tenant_id WITH =,
  table_id WITH =,
  tstzrange(reservation_start, reservation_end, '[)') WITH &&
)
WHERE (status IN ('CONFIRMED', 'SEATED') AND table_id IS NOT NULL);

CREATE OR REPLACE FUNCTION public.set_reservations_updated_at()
RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS set_reservations_updated_at
ON public.reservations;

CREATE TRIGGER set_reservations_updated_at
BEFORE UPDATE ON public.reservations
FOR EACH ROW
EXECUTE FUNCTION public.set_reservations_updated_at();
