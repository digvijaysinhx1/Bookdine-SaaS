CREATE TABLE IF NOT EXISTS public.restaurant_weekly_timings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id bigint NOT NULL,
  day_of_week smallint NOT NULL CHECK (day_of_week BETWEEN 0 AND 6),
  opening_time time NOT NULL,
  closing_time time NOT NULL,
  is_closed boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT restaurant_weekly_timings_hours_check
    CHECK (is_closed OR closing_time > opening_time),
  CONSTRAINT restaurant_weekly_timings_unique_day
    UNIQUE (tenant_id, day_of_week)
);

CREATE TABLE IF NOT EXISTS public.restaurant_closed_dates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id bigint NOT NULL,
  closed_date date NOT NULL,
  reason text,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT restaurant_closed_dates_unique_date
    UNIQUE (tenant_id, closed_date)
);

CREATE INDEX IF NOT EXISTS restaurant_weekly_timings_tenant_day_idx
ON public.restaurant_weekly_timings (tenant_id, day_of_week);

CREATE INDEX IF NOT EXISTS restaurant_closed_dates_tenant_date_idx
ON public.restaurant_closed_dates (tenant_id, closed_date)
WHERE is_active = true;

CREATE OR REPLACE FUNCTION public.set_availability_updated_at()
RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS set_restaurant_weekly_timings_updated_at
ON public.restaurant_weekly_timings;

CREATE TRIGGER set_restaurant_weekly_timings_updated_at
BEFORE UPDATE ON public.restaurant_weekly_timings
FOR EACH ROW
EXECUTE FUNCTION public.set_availability_updated_at();

DROP TRIGGER IF EXISTS set_restaurant_closed_dates_updated_at
ON public.restaurant_closed_dates;

CREATE TRIGGER set_restaurant_closed_dates_updated_at
BEFORE UPDATE ON public.restaurant_closed_dates
FOR EACH ROW
EXECUTE FUNCTION public.set_availability_updated_at();
